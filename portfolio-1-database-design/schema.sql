-- PostgreSQL schema for the University Course Registration and Results Portal.
-- Apply to a new, empty database.

CREATE TABLE department (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(12) NOT NULL,
    name VARCHAR(120) NOT NULL,
    CONSTRAINT department_code_uk UNIQUE (code),
    CONSTRAINT department_name_uk UNIQUE (name),
    CONSTRAINT department_code_not_blank CHECK (btrim(code) <> ''),
    CONSTRAINT department_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE programme (
    programme_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL,
    code VARCHAR(20) NOT NULL,
    name VARCHAR(160) NOT NULL,
    CONSTRAINT programme_department_fk
        FOREIGN KEY (department_id) REFERENCES department (department_id),
    CONSTRAINT programme_code_uk UNIQUE (code),
    CONSTRAINT programme_code_not_blank CHECK (btrim(code) <> ''),
    CONSTRAINT programme_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE student (
    student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programme_id BIGINT NOT NULL,
    matric_number VARCHAR(30) NOT NULL,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    email VARCHAR(254) NOT NULL,
    CONSTRAINT student_programme_fk
        FOREIGN KEY (programme_id) REFERENCES programme (programme_id),
    CONSTRAINT student_matric_number_uk UNIQUE (matric_number),
    CONSTRAINT student_email_uk UNIQUE (email),
    CONSTRAINT student_matric_number_not_blank CHECK (btrim(matric_number) <> ''),
    CONSTRAINT student_first_name_not_blank CHECK (btrim(first_name) <> ''),
    CONSTRAINT student_last_name_not_blank CHECK (btrim(last_name) <> ''),
    CONSTRAINT student_email_not_blank CHECK (btrim(email) <> '')
);

CREATE TABLE lecturer (
    lecturer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL,
    staff_number VARCHAR(30) NOT NULL,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    email VARCHAR(254) NOT NULL,
    CONSTRAINT lecturer_department_fk
        FOREIGN KEY (department_id) REFERENCES department (department_id),
    CONSTRAINT lecturer_staff_number_uk UNIQUE (staff_number),
    CONSTRAINT lecturer_email_uk UNIQUE (email),
    CONSTRAINT lecturer_staff_number_not_blank CHECK (btrim(staff_number) <> ''),
    CONSTRAINT lecturer_first_name_not_blank CHECK (btrim(first_name) <> ''),
    CONSTRAINT lecturer_last_name_not_blank CHECK (btrim(last_name) <> ''),
    CONSTRAINT lecturer_email_not_blank CHECK (btrim(email) <> '')
);

CREATE TABLE course (
    course_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL,
    course_code VARCHAR(20) NOT NULL,
    title VARCHAR(160) NOT NULL,
    credit_units SMALLINT NOT NULL,
    CONSTRAINT course_department_fk
        FOREIGN KEY (department_id) REFERENCES department (department_id),
    CONSTRAINT course_course_code_uk UNIQUE (course_code),
    CONSTRAINT course_credit_units_positive CHECK (credit_units > 0),
    CONSTRAINT course_course_code_not_blank CHECK (btrim(course_code) <> ''),
    CONSTRAINT course_title_not_blank CHECK (btrim(title) <> '')
);

CREATE TABLE academic_term (
    term_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year VARCHAR(9) NOT NULL,
    term_name VARCHAR(40) NOT NULL,
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    CONSTRAINT academic_term_year_name_uk UNIQUE (academic_year, term_name),
    CONSTRAINT academic_term_dates_valid CHECK (starts_on < ends_on),
    CONSTRAINT academic_term_year_not_blank CHECK (btrim(academic_year) <> ''),
    CONSTRAINT academic_term_name_not_blank CHECK (btrim(term_name) <> '')
);

CREATE TABLE course_section (
    section_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL,
    term_id BIGINT NOT NULL,
    section_code VARCHAR(20) NOT NULL,
    capacity INTEGER NOT NULL,
    CONSTRAINT course_section_course_fk
        FOREIGN KEY (course_id) REFERENCES course (course_id),
    CONSTRAINT course_section_term_fk
        FOREIGN KEY (term_id) REFERENCES academic_term (term_id),
    CONSTRAINT course_section_identity_uk UNIQUE (course_id, term_id, section_code),
    CONSTRAINT course_section_capacity_positive CHECK (capacity > 0),
    CONSTRAINT course_section_code_not_blank CHECK (btrim(section_code) <> '')
);

CREATE TABLE section_lecturer (
    section_id BIGINT NOT NULL,
    lecturer_id BIGINT NOT NULL,
    CONSTRAINT section_lecturer_pk PRIMARY KEY (section_id, lecturer_id),
    CONSTRAINT section_lecturer_section_fk
        FOREIGN KEY (section_id) REFERENCES course_section (section_id),
    CONSTRAINT section_lecturer_lecturer_fk
        FOREIGN KEY (lecturer_id) REFERENCES lecturer (lecturer_id)
);

CREATE TABLE enrolment (
    student_id BIGINT NOT NULL,
    section_id BIGINT NOT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'enrolled',
    enrolled_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT enrolment_pk PRIMARY KEY (student_id, section_id),
    CONSTRAINT enrolment_student_fk
        FOREIGN KEY (student_id) REFERENCES student (student_id),
    CONSTRAINT enrolment_section_fk
        FOREIGN KEY (section_id) REFERENCES course_section (section_id),
    CONSTRAINT enrolment_status_valid
        CHECK (status IN ('enrolled', 'dropped', 'completed'))
);

CREATE TABLE assessment (
    section_id BIGINT NOT NULL,
    assessment_no SMALLINT NOT NULL,
    title VARCHAR(120) NOT NULL,
    weight_percent NUMERIC(5, 2) NOT NULL,
    CONSTRAINT assessment_pk PRIMARY KEY (section_id, assessment_no),
    CONSTRAINT assessment_section_fk
        FOREIGN KEY (section_id) REFERENCES course_section (section_id),
    CONSTRAINT assessment_title_per_section_uk UNIQUE (section_id, title),
    CONSTRAINT assessment_number_positive CHECK (assessment_no > 0),
    CONSTRAINT assessment_weight_valid CHECK (weight_percent > 0 AND weight_percent <= 100),
    CONSTRAINT assessment_title_not_blank CHECK (btrim(title) <> '')
);

CREATE TABLE mark (
    student_id BIGINT NOT NULL,
    section_id BIGINT NOT NULL,
    assessment_no SMALLINT NOT NULL,
    score_percent NUMERIC(5, 2) NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT mark_pk PRIMARY KEY (student_id, section_id, assessment_no),
    CONSTRAINT mark_enrolment_fk
        FOREIGN KEY (student_id, section_id)
        REFERENCES enrolment (student_id, section_id),
    CONSTRAINT mark_assessment_fk
        FOREIGN KEY (section_id, assessment_no)
        REFERENCES assessment (section_id, assessment_no),
    CONSTRAINT mark_score_valid CHECK (score_percent >= 0 AND score_percent <= 100)
);

-- Preserve marks already earned if a student later drops a section, while
-- preventing marks for a dropped enrolment from being added, changed, or erased.
CREATE FUNCTION protect_marks_for_dropped_enrolment()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    target_student_id BIGINT;
    target_section_id BIGINT;
    current_enrolment_status VARCHAR(12);
BEGIN
    -- A mark's identity identifies its student, section, and assessment.
    -- Do not let an UPDATE move an existing mark to another enrolment or assessment.
    IF TG_OP = 'UPDATE'
       AND ROW(NEW.student_id, NEW.section_id, NEW.assessment_no)
           IS DISTINCT FROM ROW(OLD.student_id, OLD.section_id, OLD.assessment_no) THEN
        RAISE EXCEPTION
            'A mark identity cannot be changed; update the score only.'
            USING ERRCODE = 'check_violation';
    END IF;

    IF TG_OP = 'DELETE' THEN
        target_student_id := OLD.student_id;
        target_section_id := OLD.section_id;
    ELSIF TG_OP = 'UPDATE' THEN
        -- Updates retain the same identity, so check the existing enrolment.
        target_student_id := OLD.student_id;
        target_section_id := OLD.section_id;
    ELSE
        target_student_id := NEW.student_id;
        target_section_id := NEW.section_id;
    END IF;

    SELECT e.status
      INTO current_enrolment_status
      FROM enrolment AS e
     WHERE e.student_id = target_student_id
       AND e.section_id = target_section_id
     FOR UPDATE;

    IF current_enrolment_status = 'dropped' THEN
        RAISE EXCEPTION
            'Marks for a dropped enrolment cannot be added, changed, or deleted (student %, section %).',
            target_student_id,
            target_section_id
            USING ERRCODE = 'check_violation';
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER mark_dropped_enrolment_protection
BEFORE INSERT OR UPDATE OR DELETE ON mark
FOR EACH ROW
EXECUTE FUNCTION protect_marks_for_dropped_enrolment();
